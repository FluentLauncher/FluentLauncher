//go:build windows

package apps

import (
	"slices"
	"testing"
)

func TestAppIDAliases(t *testing.T) {
	for _, tc := range []struct {
		id, title string
		want      []string
	}{
		{"Microsoft.Windows.Explorer", "文件资源管理器", []string{"Explorer"}},
		{"Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", "计算器", []string{"WindowsCalculator", "Calculator"}},
		{`{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\cmd.exe`, "命令提示符", []string{"cmd"}},
		{`{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\services.msc`, "服务", []string{"services"}},
		{"Microsoft.AutoGenerated.{C88955BE-40D6-A9A6-67B2-A7B95C35606D}", "程序文件夹", nil},
		{`D:\Program Files\Rime\README.txt`, "说明书", nil},
		{"Chrome", "Chrome", nil},
	} {
		if got := appIDAliases(tc.id, tc.title); !slices.Equal(got, tc.want) {
			t.Fatalf("%s: aliases = %q, want %q", tc.id, got, tc.want)
		}
	}
}
